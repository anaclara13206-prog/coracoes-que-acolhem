-- Corações que Acolhem - estrutura inicial do banco PostgreSQL (Supabase)
-- Criado a partir do schema.prisma e do databaseSetup.ts do projeto enviado.
-- Banco novo/vazio: este script cria as tabelas caso ainda não existam.
-- IDs principais são INTEGER sem geração automática, exceto presenças e reset de senha.
-- Chaves estrangeiras não foram adicionadas porque o schema Prisma atual não declara relations.

CREATE TABLE IF NOT EXISTS public.usuario (
  idusuario INTEGER PRIMARY KEY,
  nomeusuario VARCHAR(80) NOT NULL,
  emailusuario VARCHAR(80) NOT NULL,
  senhausuario VARCHAR(255) NOT NULL,
  tipousuario VARCHAR(80),
  telefoneusuario VARCHAR(20),
  enderecousuario VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS public.administrador (
  idadministrador INTEGER PRIMARY KEY,
  idusuario INTEGER,
  nomeempresa VARCHAR(120),
  cnpjempresa VARCHAR(14),
  cidadeempresa VARCHAR(80),
  telefoneempresa VARCHAR(20),
  emailempresa VARCHAR(80),
  descricaoempresa TEXT,
  chavepix TEXT,
  dadosbancarios TEXT
);

CREATE TABLE IF NOT EXISTS public.voluntario (
  idvoluntario INTEGER PRIMARY KEY,
  datainscricao DATE NOT NULL,
  statusvoluntario VARCHAR(20) NOT NULL,
  disponibilidade TEXT,
  motivacao TEXT,
  experiencia TEXT,
  idade INTEGER,
  cidade VARCHAR(80),
  areainteresse VARCHAR(120),
  idusuario INTEGER,
  idquestionario INTEGER,
  idadministrador INTEGER,
  data_inicio DATE,
  data_fim DATE,
  horario_inicio VARCHAR(10),
  horario_fim VARCHAR(10)
);

CREATE TABLE IF NOT EXISTS public.doacao (
  iddoacao INTEGER PRIMARY KEY,
  valordoacao NUMERIC(10,5),
  datadoacao DATE,
  tipodoacao VARCHAR(50) NOT NULL,
  tipopagamentodoacao VARCHAR(50),
  descricaodoacao TEXT,
  idusuario INTEGER,
  idadministrador INTEGER,
  statusdoacao VARCHAR(40) NOT NULL DEFAULT 'Pendente de confirmação',
  comprovanteurl TEXT,
  motivorecusa TEXT
);

CREATE TABLE IF NOT EXISTS public.informacao (
  idinformacao INTEGER PRIMARY KEY,
  tituloinformacao VARCHAR(80) NOT NULL,
  conteudoinformacao TEXT NOT NULL,
  fonteinformacao VARCHAR(80),
  datapublicacao DATE NOT NULL,
  idadministrador INTEGER NOT NULL,
  categoria VARCHAR(60),
  imagemurl TEXT
);

CREATE TABLE IF NOT EXISTS public.questionario (
  idquestionario INTEGER PRIMARY KEY,
  respostasquestionario TEXT NOT NULL,
  dataenvioquestionario DATE NOT NULL,
  statusquestionario VARCHAR(30) NOT NULL,
  idusuario INTEGER,
  idadministrador INTEGER,
  idvoluntario INTEGER
);

CREATE TABLE IF NOT EXISTS public.contato (
  idcontato INTEGER PRIMARY KEY,
  nomecontato VARCHAR(80) NOT NULL,
  emailcontato VARCHAR(80) NOT NULL,
  assuntocontato VARCHAR(100) NOT NULL,
  mensagemcontato TEXT NOT NULL,
  datacontato DATE NOT NULL,
  idusuario INTEGER,
  idadministrador INTEGER,
  respostacontato TEXT,
  dataresposta TIMESTAMP(3)
);

CREATE TABLE IF NOT EXISTS public.voluntario_presenca (
  idpresenca INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idvoluntario INTEGER NOT NULL,
  datapresenca DATE NOT NULL,
  horainicio VARCHAR(10),
  horafim VARCHAR(10),
  status VARCHAR(20) NOT NULL DEFAULT 'presente',
  observacao TEXT
);

CREATE TABLE IF NOT EXISTS public.senha_reset (
  idreset INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idusuario INTEGER NOT NULL,
  token VARCHAR(120) NOT NULL UNIQUE,
  expiraem TIMESTAMP(3) NOT NULL,
  usadoem TIMESTAMP(3)
);

-- Índices úteis para consultas comuns e para os campos de identificação/e-mail.
CREATE INDEX IF NOT EXISTS idx_usuario_emailusuario ON public.usuario (emailusuario);
CREATE INDEX IF NOT EXISTS idx_voluntario_idusuario ON public.voluntario (idusuario);
CREATE INDEX IF NOT EXISTS idx_doacao_idusuario ON public.doacao (idusuario);
CREATE INDEX IF NOT EXISTS idx_contato_idusuario ON public.contato (idusuario);
CREATE INDEX IF NOT EXISTS idx_senha_reset_idusuario ON public.senha_reset (idusuario);

-- Fim da estrutura inicial.
